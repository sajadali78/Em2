import { MotorSpecs, CalculatedGeometry } from '../types/motor';
import { calculateWindingFactors } from './windingFunction';

export interface GoogleSheetExportResult {
  spreadsheetId: string;
  spreadsheetUrl: string;
}

export async function exportDesignToGoogleSheets(
  specs: MotorSpecs,
  geom: CalculatedGeometry,
  accessToken: string
): Promise<GoogleSheetExportResult> {
  const { harmonics, thdPct } = calculateWindingFactors(
    specs.statorSlots,
    specs.poles,
    specs.coilPitchSlots,
    specs.phases
  );

  const timestamp = new Date().toISOString().slice(0, 10);
  const sheetTitle = `Motor Design D²L - ${specs.name} (${timestamp})`;

  // 1. Create the new Spreadsheet with formatted tabs
  const createRes = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      properties: {
        title: sheetTitle,
      },
      sheets: [
        { properties: { title: 'D²L Sizing & Ratings', sheetId: 0 } },
        { properties: { title: 'Geometry & Core Details', sheetId: 1 } },
        { properties: { title: 'Winding Schedule & Harmonics', sheetId: 2 } },
        { properties: { title: 'Losses & Efficiency Map', sheetId: 3 } },
      ],
    }),
  });

  if (!createRes.ok) {
    const errBody = await createRes.text();
    throw new Error(`Failed to create Google Spreadsheet: ${createRes.status} ${errBody}`);
  }

  const sheetData = await createRes.json();
  const spreadsheetId = sheetData.spreadsheetId;

  // 2. Prepare structured data rows for each tab
  // Tab 1: D²L Sizing & Ratings
  const tab1Values = [
    ['D²L MOTOR GEOMETRY DESIGN & SIZING REPORT'],
    ['Generated by:', 'D²L Motor Geometry Design & Optimization Suite'],
    ['Date:', new Date().toLocaleString()],
    ['Motor Name:', specs.name],
    ['Machine Topology:', specs.topology.toUpperCase()],
    [],
    ['PRIMARY SPECIFICATIONS & RATINGS', '', '', ''],
    ['Parameter', 'Symbol', 'Value', 'Unit', 'Formulas & Reference'],
    ['Rated Mechanical Power', 'Pn', specs.powerKw, 'kW', 'Input target power'],
    ['Rated Line Voltage (rms)', 'Vn', specs.voltageV, 'V', 'Standard grid/inverter voltage'],
    ['Supply Frequency', 'f', specs.frequencyHz, 'Hz', 'Base electrical frequency'],
    ['Armature Poles', '2p', specs.poles, '-', 'Poles count'],
    ['Number of Phases', 'm', specs.phases, '-', '3-phase AC system'],
    ['Target Efficiency', 'eta_est', specs.targetEfficiency, '%', 'Design assumption'],
    ['Target Power Factor', 'cos(phi)', specs.targetPowerFactor, '-', 'Design assumption'],
    ['Winding Connection', 'Conn', specs.connectionType.toUpperCase(), '-', 'Star or Delta'],
    [],
    ['D²L OUTPUT EQUATION & LOADINGS', '', '', ''],
    ['Specific Magnetic Loading', 'Bav', specs.specificMagneticLoading, 'T', 'Average airgap flux density'],
    ['Specific Electric Loading', 'ac', specs.specificElectricLoading, 'A/m', 'Armature amp-conductors/m'],
    ['Core Aspect Ratio', 'lambda = L/tau', specs.aspectRatio, '-', 'Length to pole-pitch ratio'],
    ['Output Coefficient', 'C0', geom.outputCoefficientC0, 'kVA/(m³·rpm)', 'C0 = 11 * kw * Bav * ac * 10^-3'],
    ['Apparent Power', 'S', geom.apparentPowerKva, 'kVA', '=B9 / (B14/100 * B15)'],
    ['Synchronous Armature Speed', 'ns', geom.synchronousSpeedRpm, 'rpm', '=120 * B11 / B12'],
    ['Rated Rotor Speed', 'nr', geom.ratedSpeedRpm, 'rpm', 'Actual operating shaft speed'],
    ['Rated Shaft Torque', 'Tn', geom.ratedTorqueNm, 'N·m', '=(B9*1000) / (2*PI()*B25/60)'],
    ['Rated Phase Current', 'Iph', geom.phaseCurrentA, 'A', 'Current per stator phase'],
  ];

  // Tab 2: Geometry & Core Details
  const tab2Values = [
    ['STATOR AND ROTOR CORE GEOMETRY DIMENSIONS', '', '', ''],
    ['Parameter', 'Symbol', 'Value', 'Unit', 'Design Notes'],
    ['Stator Bore Inner Diameter', 'D', geom.statorBoreDiameterMm, 'mm', 'D = cbrt( (D²L * 2p) / (pi * lambda) )'],
    ['Active Core Stack Length', 'L', geom.coreLengthMm, 'mm', 'L = lambda * tau'],
    ['Pole Pitch', 'tau', geom.polePitchMm, 'mm', 'tau = pi * D / 2p'],
    ['Stator Outer Diameter', 'Do', geom.statorOuterDiameterMm, 'mm', 'Do = D + 2*hs + 2*hys'],
    ['Mechanical Airgap Length', 'g', geom.airgapLengthMm, 'mm', 'Radial clearance'],
    ['Carter Coefficient', 'kc', geom.carterCoefficient, '-', 'Effective gap multiplier'],
    ['Effective Airgap', 'ge', geom.effectiveAirgapMm, 'mm', 'ge = kc * g'],
    ['Rotor Outer Diameter', 'Dr', geom.rotorOuterDiameterMm, 'mm', 'Dr = D - 2*g'],
    ['Shaft Diameter', 'Dsh', geom.shaftDiameterMm, 'mm', 'Torque transmission sizing'],
    [],
    ['STATOR SLOT & TOOTH SIZING', '', '', ''],
    ['Total Stator Slots', 'Qs', specs.statorSlots, '-', 'Punching lamination slots'],
    ['Stator Slot Pitch', 'tau_s', geom.slotPitchMm, 'mm', 'tau_s = pi * D / Qs'],
    ['Stator Tooth Width', 'bts', geom.toothWidthMm, 'mm', 'Sized for max tooth flux density'],
    ['Estimated Tooth Flux Density', 'Bts', geom.toothFluxDensityTesla, 'T', 'Peak tooth saturation check'],
    ['Slot Opening Width', 'bs0', geom.slotOpeningWidthMm, 'mm', 'Semi-closed entry slot'],
    ['Slot Width (Top)', 'bs1', geom.slotWidthTopMm, 'mm', 'Tooth parallel edge'],
    ['Slot Width (Bottom)', 'bs2', geom.slotWidthBottomMm, 'mm', 'Wedge base edge'],
    ['Total Slot Depth', 'hs', geom.slotDepthMm, 'mm', 'Winding insertion depth'],
    ['Total Slot Area', 'Aslot', geom.slotAreaMm2, 'mm²', 'Gross slot volume'],
    ['Stator Yoke (Back-Iron) Depth', 'hys', geom.statorYokeDepthMm, 'mm', 'Back-iron flux return path'],
    ['Stator Yoke Flux Density', 'Bys', geom.yokeFluxDensityTesla, 'T', 'Yoke saturation check'],
  ];

  // Tab 3: Winding Schedule & Harmonics
  const tab3Values = [
    ['STATOR WINDING DESIGN & HARMONIC FUNCTION', '', '', ''],
    ['Parameter', 'Symbol', 'Value', 'Unit', 'Description'],
    ['Slots per Pole per Phase', 'q', geom.slotsPerPolePerPhase, '-', 'q = Qs / (2p * m)'],
    ['Coil Pitch in Slots', 'ys', specs.coilPitchSlots, 'slots', 'Chording pitch'],
    ['Fundamental Distribution Factor', 'kd1', geom.distributionFactorKd, '-', 'Slot distribution'],
    ['Fundamental Pitch Factor', 'kp1', geom.pitchFactorKp, '-', 'Short-pitch factor'],
    ['Fundamental Winding Factor', 'kw1', geom.windingFactorKw, '-', 'kw = kd * kp'],
    ['Turns per Phase in Series', 'Nph', geom.turnsPerPhase, '-', 'Active turns'],
    ['Conductors per Slot', 'Zs', geom.conductorsPerSlot, '-', 'Double-layer total conductors'],
    ['Slot Fill Factor (Copper/Slot)', 'kfill', geom.actualSlotFillFactor, '-', 'Manufacturability (<0.45)'],
    ['Current Density', 'J', geom.actualCurrentDensityA_mm2, 'A/mm²', 'Thermal loading'],
    ['Stator Phase Resistance at 75°C', 'Rs', geom.statorResistancePerPhaseOhm, 'Ohm', 'Per phase DC resistance'],
    ['Winding MMF THD', 'THD', thdPct, '%', 'Total Harmonic Distortion'],
    [],
    ['HARMONIC WINDING FACTOR SPECTRUM', '', '', ''],
    ['Harmonic Order (nu)', 'kd(nu)', 'kp(nu)', 'kw(nu)', 'Relative Amplitude (%)'],
    ...harmonics.map((h) => [h.order, h.kd, h.kp, h.kw, h.relativeAmplitudePct]),
  ];

  // Tab 4: Losses & Efficiency Map
  const tab4Values = [
    ['LOSS BREAKDOWN & EFFICIENCY OPTIMIZATION', '', '', ''],
    ['Loss Component', 'Symbol', 'Loss (W)', 'Percentage of Total (%)', 'Engineering Comments'],
    [
      'Stator Copper Loss (Total)',
      'Pcu_s',
      geom.statorCopperLossW,
      `${((geom.statorCopperLossW / geom.totalLossW) * 100).toFixed(1)}%`,
      `DC: ${geom.statorCopperLossDcW} W, AC: ${geom.statorCopperLossAcW} W (kac = ${geom.acResistanceFactorKac} at ${specs.frequencyHz} Hz, ${geom.copperTemperatureC}°C)`,
    ],
    [
      'Rotor Loss (Joule / Magnet Eddy)',
      'Pcu_r / Pmag',
      geom.rotorLossW,
      `${((geom.rotorLossW / geom.totalLossW) * 100).toFixed(1)}%`,
      specs.topology === 'induction' ? 'Slip airgap power dissipation' : 'Magnet eddy current dissipation',
    ],
    [
      'Stator Core Iron Loss (Total)',
      'Pfe',
      geom.ironCoreLossW,
      `${((geom.ironCoreLossW / geom.totalLossW) * 100).toFixed(1)}%`,
      `Hysteresis: ${geom.ironCoreHysteresisLossW} W, Eddy-Current: ${geom.ironCoreEddyLossW} W (p_fe0 = ${geom.specificIronLossW_kg} W/kg)`,
    ],
    [
      'Friction & Windage Loss',
      'Pmw',
      geom.mechanicalLossW,
      `${((geom.mechanicalLossW / geom.totalLossW) * 100).toFixed(1)}%`,
      'Bearings and ventilation air drag',
    ],
    [
      'Stray Load Losses',
      'Pstray',
      geom.strayLoadLossW,
      `${((geom.strayLoadLossW / geom.totalLossW) * 100).toFixed(1)}%`,
      'Harmonic leakage flux losses',
    ],
    ['TOTAL LOSSES', 'Ploss', geom.totalLossW, '100.0%', 'Sum of all active losses'],
    [],
    ['ELECTROMAGNETIC PERFORMANCE SUMMARY', '', '', ''],
    ['Metric', 'Symbol', 'Value', 'Unit', 'Target Comparison'],
    ['Calculated Efficiency', 'eta', geom.calculatedEfficiency, '%', `Initial Target: ${specs.targetEfficiency}%`],
    ['Active Power Density', 'Power Dens', geom.powerDensityKw_m3, 'kW/m³', 'Volumetric power density'],
    ['Torque Density', 'Torque Dens', geom.torqueDensityNm_m3, 'N·m/m³', 'Core torque density'],
    ['Active Steel Core Weight', 'M_steel', geom.totalActiveSteelWeightKg, 'kg', 'Lamination weight'],
    ['Active Copper Wire Weight', 'M_copper', geom.totalCopperWeightKg, 'kg', 'Winding mass'],
  ];

  // 3. Batch Update values into spreadsheet
  const batchRes = await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values:batchUpdate`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        valueInputOption: 'USER_ENTERED',
        data: [
          { range: "'D²L Sizing & Ratings'!A1", values: tab1Values },
          { range: "'Geometry & Core Details'!A1", values: tab2Values },
          { range: "'Winding Schedule & Harmonics'!A1", values: tab3Values },
          { range: "'Losses & Efficiency Map'!A1", values: tab4Values },
        ],
      }),
    }
  );

  if (!batchRes.ok) {
    const errText = await batchRes.text();
    console.warn('Batch update values warning:', errText);
  }

  return {
    spreadsheetId,
    spreadsheetUrl: `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`,
  };
}
